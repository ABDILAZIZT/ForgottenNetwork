export function colorCube(vip: boolean) {
  const levels = vip ? 8 : 4;
  return Array.from({ length: levels * levels * 4 }, (_, index) => {
    const channels = [
      (Math.floor(index / (levels * 4)) * 255) / (levels - 1),
      ((Math.floor(index / 4) % levels) * 255) / (levels - 1),
      (index % 4) * 85,
    ];
    return (
      '#' + channels.map((channel) => Math.round(channel).toString(16).padStart(2, '0')).join('')
    );
  });
}
